#!/usr/bin/env python3
"""Generate the Chher launcher icon from one geometry definition.

Writes:
  brand/chher-icon.svg                                 design source (108x108 adaptive canvas)
  android/.../drawable/ic_launcher_background.xml      gradient layer
  android/.../drawable/ic_launcher_foreground.xml      white "ch / er" strokes, also the themed-icon layer
  android/.../mipmap-anydpi-v26/ic_launcher.xml        adaptive icon (Android 8+, monochrome for 13+)
  android/.../mipmap-*/ic_launcher.png                 legacy bitmaps for Android 7.x
  assets/brand/chher-logo.png                          in-app logo (about page); corners are clipped in Flutter

The legacy bitmaps are rendered with macOS Quick Look (qlmanage) and Pillow.
Run from the repository root:  python3 tool/launcher_icon.py
"""
import os
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "android", "app", "src", "main", "res")

TOP, BOTTOM = "#BE2A33", "#8E1219"
STROKE = 6.0
# The block is drawn at natural size and scaled about the centre so that it
# fills ~64% of the visible 72dp window of the 108dp adaptive canvas.
SCALE = 0.6866
PATHS = [
    "M49.37,47.57 A10,10 0 1 1 49.37,33.43",                     # c
    "M61.3,23.5 L61.3,50.5",                                       # h stem
    "M61.3,37.7 A7.2,7.2 0 0 1 75.7,37.7 L75.7,50.5",              # h shoulder
    "M49.96,80.93 A10,10 0 1 1 52.3,74.5",                        # e bowl
    "M32.3,74.5 L52.3,74.5",                                       # e bar
    "M61.3,64.5 L61.3,84.5",                                       # r stem
    "M61.3,72.78 A8.28,8.28 0 0 1 69.58,64.5 L71.68,64.5",         # r arm
]
LEGACY = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}


def write(rel, text):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def svg(view_box="0 0 108 108", size=108):
    paths = "".join(
        f'<path d="{d}" fill="none" stroke="#FFFFFF" stroke-width="{STROKE}" '
        f'stroke-linecap="round" stroke-linejoin="round"/>' for d in PATHS
    )
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{view_box}" width="{size}" height="{size}">'
        f'<defs><linearGradient id="g" gradientUnits="userSpaceOnUse" x1="0" y1="0" x2="0" y2="108">'
        f'<stop offset="0" stop-color="{TOP}"/><stop offset="1" stop-color="{BOTTOM}"/></linearGradient></defs>'
        f'<rect width="108" height="108" fill="url(#g)"/>'
        f'<g transform="translate(54 54) scale({SCALE}) translate(-54 -54)">{paths}</g></svg>\n'
    )


def android_xml():
    write("android/app/src/main/res/drawable/ic_launcher_background.xml", f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/launcher_icon.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="linear"
                android:startX="0"
                android:startY="0"
                android:endX="0"
                android:endY="108">
                <item android:offset="0" android:color="#FF{TOP[1:]}" />
                <item android:offset="1" android:color="#FF{BOTTOM[1:]}" />
            </gradient>
        </aapt:attr>
    </path>
</vector>
""")
    strokes = "\n".join(f"""        <path
            android:pathData="{d}"
            android:strokeColor="#FFFFFFFF"
            android:strokeWidth="{STROKE}"
            android:strokeLineCap="round"
            android:strokeLineJoin="round" />""" for d in PATHS)
    write("android/app/src/main/res/drawable/ic_launcher_foreground.xml", f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/launcher_icon.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:pivotX="54"
        android:pivotY="54"
        android:scaleX="{SCALE}"
        android:scaleY="{SCALE}">
{strokes}
    </group>
</vector>
""")
    write("android/app/src/main/res/mipmap-anydpi-v26/ic_launcher.xml", """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/launcher_icon.py -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <!-- Android 13 themed icons tint this layer's shape -->
    <monochrome android:drawable="@drawable/ic_launcher_foreground" />
</adaptive-icon>
""")


def render_visible_window(work):
    """The visible 72dp window of the adaptive canvas as a 1024px square."""
    from PIL import Image

    src = os.path.join(work, "window.svg")
    with open(src, "w") as f:
        f.write(svg(view_box="18 18 72 72", size=1024))
    subprocess.run(["qlmanage", "-t", "-s", "1024", "-o", work, src],
                   check=True, capture_output=True)
    return Image.open(src + ".png").convert("RGBA").resize((1024, 1024), Image.LANCZOS)


def app_logo():
    """Square, unrounded: the app clips it with its own corner radius."""
    from PIL import Image

    work = tempfile.mkdtemp()
    try:
        out = os.path.join(ROOT, "assets", "brand", "chher-logo.png")
        os.makedirs(os.path.dirname(out), exist_ok=True)
        render_visible_window(work).resize((512, 512), Image.LANCZOS).save(out, optimize=True)
    finally:
        shutil.rmtree(work, ignore_errors=True)


def legacy_pngs():
    """Android 7.x has no adaptive icons: ship the visible 72dp window as a rounded square."""
    from PIL import Image, ImageDraw

    work = tempfile.mkdtemp()
    try:
        full = render_visible_window(work)
        mask = Image.new("L", (1024, 1024), 0)
        ImageDraw.Draw(mask).rounded_rectangle((0, 0, 1023, 1023), radius=230, fill=255)
        full.putalpha(mask)
        for density, px in LEGACY.items():
            out = os.path.join(RES, f"mipmap-{density}", "ic_launcher.png")
            full.resize((px, px), Image.LANCZOS).save(out, optimize=True)
    finally:
        shutil.rmtree(work, ignore_errors=True)


if __name__ == "__main__":
    if not os.path.isdir(RES):
        sys.exit("run from the repository root")
    write("brand/chher-icon.svg", svg())
    android_xml()
    legacy_pngs()
    app_logo()
    print("launcher icon generated")
