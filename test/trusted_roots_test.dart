class _Client extends Fake implements HttpClient {}

void main() {
  test('追加的两个公共根可被 SecurityContext 接受且内容与给定 PEM 一致', () {
    expect(buildTrustContext, returnsNormally);
    final certificates = RegExp(
      r'-----BEGIN CERTIFICATE-----\n(.*?)-----END CERTIFICATE-----',
      dotAll: true,
    ).allMatches(sectigoPublicRootsPem).toList();
    expect(certificates, hasLength(2));
    for (var i = 0; i < certificates.length; i++) {
      final body = certificates[i].group(1)!;
      expect(body, _expectedBodies[i]);
      final der = base64.decode(body.replaceAll(RegExp(r'\s'), ''));
      final name =
          'Sectigo Public Server Authentication Root ${i == 0 ? 'E46' : 'R46'}';
      expect(latin1.decode(der), contains(name));
      final native = File(
        'android/app/src/main/res/raw/sectigo_${i == 0 ? 'e46' : 'r46'}.crt',
      ).readAsStringSync();
      expect(native, '${certificates[i].group(0)!}\n');
    }
  });

  test('HttpOverrides.current 覆盖默认 HttpClient 并复用追加根上下文', () {
    final previous = HttpOverrides.current;
    final context = buildTrustContext();
    final client = _Client();
    var builds = 0;
    final contexts = <SecurityContext>[];
    final overrides = ChhHttpOverrides(
      contextFactory: () {
        builds++;
        return context;
      },
      clientFactory: (value) {
        contexts.add(value);
        return client;
      },
    );
    HttpOverrides.global = overrides;
    addTearDown(() => HttpOverrides.global = previous);
    expect(HttpOverrides.current, same(overrides));
    expect(HttpClient(), same(client));
    expect(HttpClient(), same(client));
    expect(builds, 1);
    expect(contexts, [same(context), same(context)]);
    final explicit = SecurityContext();
    expect(HttpClient(context: explicit), same(client));
    expect(contexts.last, same(explicit));
    expect(builds, 1);
  });
}
